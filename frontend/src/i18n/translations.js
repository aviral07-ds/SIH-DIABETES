export function getLocalizedStageInfo(stageCode, defaultTitle, isHi) {
  const code = Number(stageCode);
  if (isHi) {
    switch (code) {
      case 0: return { title: "कोई डायबिटिक रेटिनोपैथी नहीं (सामान्य फंडस)", badge: "ICDR स्टेज 0 • सामान्य" };
      case 1: return { title: "हल्की गैर-प्रोलिफेरेटिव डायबिटिक रेटिनोपैथी (माइल्ड NPDR)", badge: "ICDR स्टेज 1 • हल्का" };
      case 2: return { title: "मध्यम गैर-प्रोलिफेरेटिव डायबिटिक रेटिनोपैथी (मॉडरेट NPDR)", badge: "ICDR स्टेज 2 • मध्यम" };
      case 3: return { title: "गंभीर गैर-प्रोलिफेरेटिव डायबिटिक रेटिनोपैथी (सिवियर NPDR)", badge: "ICDR स्टेज 3 • गंभीर" };
      case 4: return { title: "प्रोलिफेरेटिव डायबिटिक रेटिनोपैथी (PDR)", badge: "ICDR स्टेज 4 • प्रोलिफेरेटिव" };
      default: return { title: defaultTitle || "डायबिटिक रेटिनोपैथी", badge: `ICDR स्टेज ${code || 2}` };
    }
  }
  switch (code) {
    case 0: return { title: "No Apparent DR (Normal Fundus)", badge: "ICDR Stage 0 • Normal" };
    case 1: return { title: "Mild Non-Proliferative DR (Mild NPDR)", badge: "ICDR Stage 1 • Mild" };
    case 2: return { title: "Moderate Non-Proliferative DR (Moderate NPDR)", badge: "ICDR Stage 2 • Moderate" };
    case 3: return { title: "Severe Non-Proliferative DR (Severe NPDR)", badge: "ICDR Stage 3 • Severe" };
    case 4: return { title: "Proliferative Diabetic Retinopathy (PDR)", badge: "ICDR Stage 4 • Proliferative" };
    default: return { title: defaultTitle || "Moderate Non-Proliferative DR", badge: `ICDR Stage ${code || 2}` };
  }
}

export function getLocalizedEye(eyeStr, isHi) {
  if (!eyeStr) return isHi ? "OD [दाहिनी आंख]" : "OD [Right Eye]";
  const upper = eyeStr.toUpperCase();
  if (upper.includes('OS') || upper.includes('LEFT') || upper.includes('बायाँ') || upper.includes('बायें')) {
    return isHi ? "OS [बायें आंख]" : "OS [Left Eye]";
  }
  return isHi ? "OD [दाहिनी आंख]" : "OD [Right Eye]";
}

